#!/usr/bin/env python3
"""Write environment/docker-compose.yaml for a task so its trials run behind netguard.

    python3 harness/netguard/write_compose.py <task-dir> [<task-dir> ...]

Blocked: the task repo (from task.toml [metadata].repo) and NAMES[task] = repo name plus the
package names it is published under. The compose file adds the `netguard` sidecar (built from
this folder) and puts Harbor's `main` service into its network namespace.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
# Names the task's code is published under (registries / CDNs), beyond the repo name.
NAMES = {
    "actualbudget": ["actual", "sync-server", "@actual-app"],
    "argo-workflows": ["argo-workflows"],
    "async-http-client": ["async-http-client"],
    "asyncssh": ["asyncssh"],
    "cloudreve": ["cloudreve"],
    "filament": ["filament"],
    "hickory-dns": ["hickory-dns", "hickory-resolver", "hickory-proto", "hickory-server",
                    "hickory-client", "hickory-recursor", "trust-dns-resolver", "trust-dns-proto"],
    "jackson-databind": ["jackson-databind"],
    "jackson-databind-sib": ["jackson-databind"],
    "jackson-sib7": ["jackson-databind"],
    "py-shiny": ["py-shiny", "shiny"],
    "rclone": ["rclone"],
    "rclone-sib": ["rclone"],
    "ruby-saml": ["ruby-saml"],
    "russh": ["russh", "russh-keys", "russh-cryptovec", "russh-util", "russh-config"],
    "russh-sib": ["russh", "russh-keys", "russh-cryptovec", "russh-util", "russh-config"],
    "stigmem": ["stigmem", "stigmem-node"],
    "trigger-dev": ["trigger.dev", "@trigger.dev"],
    "webob": ["webob"],
}
CA_ENV = {
    "SSL_CERT_FILE": "/netguard-certs/bundle.pem",
    "REQUESTS_CA_BUNDLE": "/netguard-certs/bundle.pem",
    "CURL_CA_BUNDLE": "/netguard-certs/bundle.pem",
    "GIT_SSL_CAINFO": "/netguard-certs/bundle.pem",
    "PIP_CERT": "/netguard-certs/bundle.pem",
    "CARGO_HTTP_CAINFO": "/netguard-certs/bundle.pem",
    "NODE_EXTRA_CA_CERTS": "/netguard-certs/netguard-ca.pem",
    "npm_config_cafile": "/netguard-certs/bundle.pem",
}


def compose(task_dir: Path) -> str:
    t = (task_dir / "task.toml").read_text()
    m = re.search(r'repo\s*=\s*"https?://(?:www\.)?(?:github|gitlab)\.com/([^/"]+)/([^/"]+?)(?:\.git)?"', t)
    if not m:
        raise SystemExit(f"{task_dir}: no github/gitlab repo in task.toml")
    owner_repo = f"{m.group(1)}/{m.group(2)}"
    names = sorted({m.group(2), *NAMES.get(task_dir.name, [])})
    rel = Path("../../../harness/netguard")              # tasks/<task>/environment -> harness/netguard
    env = "\n".join(f'      {k}: "{v}"' for k, v in CA_ENV.items())
    return f'''# Generated by harness/netguard/write_compose.py — do not edit by hand.
# Client trial rule: internet, but no access to the task's own repository. The `main` service runs
# in the netguard sidecar's network namespace; netguard refuses {owner_repo} (and forks/mirrors and
# its published packages: {" ".join(names)}) on every route and passes everything else through.
services:
  netguard:
    build:
      context: {rel}
    image: cwe-netguard:1
    cap_add: [NET_ADMIN, NET_RAW]
    environment:
      NETGUARD_BLOCK_REPOS: "{owner_repo}"
      NETGUARD_BLOCK_NAMES: "{" ".join(names)}"
    volumes:
      - netguard-certs:/netguard-certs
    healthcheck:
      test: ["CMD", "test", "-f", "/tmp/netguard.ready"]
      interval: 1s
      timeout: 5s
      retries: 60
  main:
    network_mode: "service:netguard"
    depends_on:
      netguard:
        condition: service_healthy
    volumes:
      - netguard-certs:/netguard-certs:ro
    environment:
{env}
volumes:
  netguard-certs: {{}}
'''


if __name__ == "__main__":
    for d in sys.argv[1:]:
        d = Path(d).resolve()
        (d / "environment" / "docker-compose.yaml").write_text(compose(d))
        print("wrote", d / "environment" / "docker-compose.yaml")
