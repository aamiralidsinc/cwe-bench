#!/usr/bin/env python3
"""One row per task: its properties next to each model's result (research/own-runs).

    python3 research/own-runs/task_table.py

Inputs: tasks/<task>/task.toml [metadata], tasks/<task>/solution/fix.patch (reference fix shape),
build/audit/trials.tsv (verdict source) and test_results.tsv (test_matrix.py, per-test outcomes).
Output: task_table.md and task_table.tsv in this folder.
Per model: solved/graded (runs used in verdicts), mean share of security tests passed, mean share
of functional tests passed, median agent minutes. 'items' = distinct security test suites.
"""
import csv
import re
import statistics
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "build"))
import audit_results as A                                    # noqa: E402

MODELS = {"deepseek-flash[1m]": "DeepSeek", "mimo-v2.6-pro": "MiMo"}


def meta(task):
    t = (ROOT / "tasks" / task / "task.toml").read_text()
    get = lambda k: (re.search(rf'^{k}\s*=\s*"([^"]*)"', t, re.M) or [None, ""])[1]
    return {"language": get("language"), "cwes": get("cwe_id"), "source": get("source")}


def fix_shape(task):
    p = ROOT / "tasks" / task / "solution" / "fix.patch"
    files, hunks, plus, minus = set(), 0, 0, 0
    for line in p.read_text(errors="replace").splitlines():
        if line.startswith("+++ b/"):
            files.add(line[6:])
        elif line.startswith("@@"):
            hunks += 1
        elif line.startswith("+") and not line.startswith("+++"):
            plus += 1
        elif line.startswith("-") and not line.startswith("---"):
            minus += 1
    src = [f for f in files if not re.search(r"(^|/)(test|tests|__tests__|spec)(/|$)|_test\.|\.test\.|Test\.java$", f)]
    return len(src), hunks, plus + minus


def main():
    tests = defaultdict(lambda: defaultdict(list))       # trial -> kind -> [ok...]
    used = {}
    suites = defaultdict(set)
    for r in csv.DictReader(open(HERE / "test_results.tsv"), delimiter="\t"):
        key = r["trial"]
        used[key] = r["used_in_verdict"] == "1"
        if r["outcome"] != "skip":
            tests[key][r["kind"]].append(r["outcome"] == "pass")
        if r["kind"] == "security":
            suites[r["task"]].add(r["suite"])
    trials = list(csv.DictReader(open(ROOT / "build/audit/trials.tsv"), delimiter="\t"))
    tasks = sorted({t["task"] for t in trials}, key=lambda t: (["mined", "stacking", "injection"].index(A.track_of(t)), t))
    rows = []
    for task in tasks:
        m = meta(task)
        nfiles, hunks, lines = fix_shape(task)
        row = {"track": A.track_of(task), "task": task, "language": m["language"], "cwes": m["cwes"],
               "items": len(suites[task]), "fix_files": nfiles, "fix_hunks": hunks, "fix_lines": lines}
        for model, name in MODELS.items():
            runs = [t for t in trials if t["task"] == task and t["model"] == model and t["reward"] != ""
                    and used.get(t["trial"], False)]
            sec = [sum(tests[t["trial"]]["security"]) / max(1, len(tests[t["trial"]]["security"])) for t in runs]
            fn = [sum(tests[t["trial"]]["functional"]) / max(1, len(tests[t["trial"]]["functional"])) for t in runs]
            mins = [float(t["agent_min"]) for t in runs if t["agent_min"]]
            row[f"{name}_solved"] = f"{sum(float(t['reward']) == 1.0 for t in runs)}/{len(runs)}"
            row[f"{name}_sec"] = f"{statistics.mean(sec):.0%}" if sec else ""
            row[f"{name}_fn"] = f"{statistics.mean(fn):.0%}" if fn else ""
            row[f"{name}_min"] = f"{statistics.median(mins):.0f}" if mins else ""
        rows.append(row)
    cols = list(rows[0])
    with open(HERE / "task_table.tsv", "w") as f:
        f.write("\t".join(cols) + "\n")
        for r in rows:
            f.write("\t".join(str(r[c]) for c in cols) + "\n")
    with open(HERE / "task_table.md", "w") as f:
        f.write("# Task properties and per-model results\n\n_Generated by task_table.py from build/audit/trials.tsv "
                "and test_results.tsv (runs used in verdicts only). sec/fn = mean share of security/functional "
                "tests passed; min = median agent minutes; fix = reference fix: source files / hunks / changed lines._\n\n")
        f.write("| Track | Task | Lang | Items | Fix | DS solved | DS sec | DS fn | DS min | MiMo solved | MiMo sec | MiMo fn | MiMo min |\n")
        f.write("|---|---|---|---|---|---|---|---|---|---|---|---|---|\n")
        for r in rows:
            f.write(f"| {r['track']} | {r['task']} | {r['language']} | {r['items']} | {r['fix_files']}/{r['fix_hunks']}/{r['fix_lines']} "
                    f"| {r['DeepSeek_solved']} | {r['DeepSeek_sec']} | {r['DeepSeek_fn']} | {r['DeepSeek_min']} "
                    f"| {r['MiMo_solved']} | {r['MiMo_sec']} | {r['MiMo_fn']} | {r['MiMo_min']} |\n")
    print(f"{len(rows)} tasks -> task_table.md")


if __name__ == "__main__":
    main()
