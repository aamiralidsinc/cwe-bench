#!/usr/bin/env python3
"""Per-test pass/fail of every graded trial: which planted vulnerability each model missed.

    python3 research/own-runs/test_matrix.py

Trials and verdicts come ONLY from build/audit/trials.tsv (written by build/audit_results.py, the
single source of truth). For each graded trial this reads the JUnit files of the grading the audit
used (verifier/ for 'original', <trial>/<regrade-*>/verifier/ otherwise): <grading>/results.json
({"security": {test: pass|fail}, "functional": {...}}, written by every task's score.py), falling
back to the JUnit files <grading>/<kind>/results.xml.
Output (this folder):
    test_results.tsv  task, model, start_utc, trial, reward, used_in_verdict, kind, suite, test, outcome
    matrix.md         per task: one row per security test, pass counts per model
A trial counts toward the verdict when the audit's note does not mark it excluded (ungraded, cut at
60 min, leaked tests, grader fault); those runs are still listed, marked used_in_verdict=0.
"""
import csv
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
JOBS = Path.home() / ".tb-graders" / "cwe" / "jobs"
MODELS = {"deepseek-flash[1m]": "DeepSeek", "mimo-v2.6-pro": "MiMo"}


sys.path.insert(0, str(ROOT / "build"))
import audit_results as A                                    # noqa: E402  (same exclusion rules)


def used_in_verdict(r, leaked, decided):
    """Mirror of audit_results.cell(): leaked tests, cut by a shorter limit, and flagged runs not
    reviewed as 'model' are excluded from the verdict."""
    if (r["job"], r["trial"]) in leaked:
        return 0
    if r["timed_out"] == "True" and int(r["limit_sec"]) < A.task_limit(r["task"]) and float(r["reward"]) != 1.0:
        return 0
    if r["flags"] and decided.get((r["job"], r["trial"], r["grading"] or "original")) != "model":
        return 0
    return 1


def results(gdir, kind):
    p = gdir / "results.json"
    if p.exists():
        d = A.jload(p) or {}
        if d.get(kind):
            out = []
            for name, res in d[kind].items():
                suite, _, test = name.rpartition("::")
                out.append((suite, test, "pass" if res == "pass" else "skip" if res == "skip" else "fail"))
            return out
    return junit(gdir / kind / "results.xml")


def junit(path):
    if not path.exists():
        return []
    out = []
    for tc in ET.parse(path).getroot().iter("testcase"):
        suite = Path(tc.get("classname") or "").name
        bad = tc.find("failure") is not None or tc.find("error") is not None
        skipped = tc.find("skipped") is not None
        out.append((suite, tc.get("name"), "skip" if skipped else "fail" if bad else "pass"))
    return out


def main():
    rows = list(csv.DictReader(open(ROOT / "build/audit/trials.tsv"), delimiter="\t"))
    leaked, decided = A.contaminated(), A.reviews()
    out = []
    for r in rows:
        if r["reward"] == "":
            continue
        tdir = JOBS / r["job"] / r["trial"]
        g = tdir / "verifier" if r["grading"] in ("", "original") else tdir / r["grading"] / "verifier"
        used = used_in_verdict(r, leaked, decided)
        for kind in ("security", "functional"):
            for suite, test, res in results(g, kind):
                out.append([r["task"], MODELS.get(r["model"], r["model"]), r["start_utc"], r["trial"], r["reward"],
                            used, kind, suite, test, res])
    with open(HERE / "test_results.tsv", "w") as f:
        f.write("task\tmodel\tstart_utc\ttrial\treward\tused_in_verdict\tkind\tsuite\ttest\toutcome\n")
        for o in out:
            f.write("\t".join(map(str, o)) + "\n")

    cnt = defaultdict(lambda: defaultdict(lambda: [0, 0]))       # (task) -> (kind,suite,test,model) -> [pass, n]
    for task, model, _s, _t, _r, used, kind, suite, test, res in out:
        if used and res != "skip":
            c = cnt[task][(kind, suite, test, model)]
            c[0] += res == "pass"
            c[1] += 1
    with open(HERE / "matrix.md", "w") as f:
        f.write("# Tests passed per model (graded runs used in verdicts)\n\n"
                "_Generated by test_matrix.py from build/audit/trials.tsv. Cell = runs passing / graded runs. "
                "All security tests are listed; functional tests only when some run failed them._\n")
        for task in sorted(cnt):
            keys = sorted({(k, s, t) for k, s, t, _m in cnt[task]}, key=lambda x: (x[0] != "security", x))
            f.write(f"\n## {task}\n\n| Kind | Suite | Test | DeepSeek | MiMo |\n|---|---|---|---|---|\n")
            for k, s, t in keys:
                if k == "functional" and all(cnt[task].get((k, s, t, m), [0, 0])[0] == cnt[task].get((k, s, t, m), [0, 0])[1]
                                             for m in ("DeepSeek", "MiMo")):
                    continue
                cells = []
                for m in ("DeepSeek", "MiMo"):
                    p, n = cnt[task].get((k, s, t, m), [0, 0])
                    cells.append("–" if n == 0 else (f"**{p}/{n}**" if p < n else f"{p}/{n}"))
                f.write(f"| {k[:4]} | {s} | {t.replace('|', '/')} | {cells[0]} | {cells[1]} |\n")
    print(f"{len(out)} test results from {len({o[3] for o in out})} graded trials")


if __name__ == "__main__":
    main()
