package security

import (
	"testing"

	htests "github.com/fabiolb/fabio/htests_support"
)

func startGRPCProxy(t *testing.T, backend string) *htests.Fabio {
	t.Helper()
	return htests.StartFabio(t, htests.FreeAddr(t)+";proto=grpc",
		"-registry.static.routes", htests.GRPCRoute(backend),
		"-proxy.header.clientip", "X-Client-IP",
		"-proxy.header.requestid", "X-Request-ID",
		"-proxy.header.tls", "X-Secure")
}

// The client-address header configured by the operator must reach a gRPC
// backend with the value the proxy observed, not the client's value.
func TestSec_GRPCClientIPIsFabios(t *testing.T) {
	backend, calls := htests.GRPCBackend(t)
	f := startGRPCProxy(t, backend)

	_ = htests.GRPCCall(f.Addr(),
		"x-client-ip", "9.9.9.9",
		"x-request-id", "attacker-id",
		"x-secure", "attacker-tls")

	md := htests.RecvMetadata(t, calls)
	got := md.Get("x-client-ip")
	if len(got) != 1 || !htests.IsLoopbackValue(got[0]) {
		t.Errorf("backend saw x-client-ip %v, want the value derived from the client address", got)
	}
}

// The request id configured by the operator must be generated by the proxy,
// not supplied by the client.
func TestSec_GRPCRequestIDIsFabios(t *testing.T) {
	backend, calls := htests.GRPCBackend(t)
	f := startGRPCProxy(t, backend)

	_ = htests.GRPCCall(f.Addr(),
		"x-client-ip", "9.9.9.9",
		"x-request-id", "attacker-id",
		"x-secure", "attacker-tls")

	md := htests.RecvMetadata(t, calls)
	got := md.Get("x-request-id")
	if len(got) != 1 || got[0] == "" || got[0] == "attacker-id" {
		t.Errorf("backend saw x-request-id %v, want a value the proxy generated", got)
	}
}

// The TLS assertion configured by the operator must not be taken from the
// client. This connection is not TLS, so the value must be absent.
func TestSec_GRPCTLSHeaderIsNotClientSupplied(t *testing.T) {
	backend, calls := htests.GRPCBackend(t)
	f := startGRPCProxy(t, backend)

	_ = htests.GRPCCall(f.Addr(),
		"x-client-ip", "9.9.9.9",
		"x-request-id", "attacker-id",
		"x-secure", "attacker-tls")

	md := htests.RecvMetadata(t, calls)
	if got := md.Get("x-secure"); len(got) != 0 {
		t.Errorf("backend saw x-secure %v, want no client-supplied value", got)
	}
}
